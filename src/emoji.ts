const EMOJI_RE = /:([a-z0-9_+\-]+):/g;

/** ':shortcode:' → unicode where the code is known; unknown codes pass
 *  through untouched. */
export function demojize(text: string): string {
  return text.replace(EMOJI_RE, (m, name: string) => EMOJI_CODES[name] ?? m);
}
